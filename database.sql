-- FOOD BRIDGE - ENHANCED SUPABASE DATABASE
-- Run this entire script in Supabase Dashboard -> SQL Editor.

create table if not exists public.donations (
  id bigint generated by default as identity primary key,
  donor_name text not null,
  food text not null,
  category text not null,
  qty text not null,
  address text not null,
  phone text not null,
  image text,
  accepted boolean not null default false,
  accepted_by text,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  reported boolean not null default false,
  report_reason text,
  reported_by text,
  reported_at timestamptz
);

create table if not exists public.receivers (
  user_name text primary key,
  password text not null,
  phone text not null
);

create table if not exists public.admin_accounts (
  username text primary key,
  password text not null,
  phone text not null
);

-- Add phone to an existing admin_accounts table if it was created earlier.
alter table public.admin_accounts add column if not exists phone text;
update public.admin_accounts set phone = '7981180556' where username = 'admin' and (phone is null or phone = '');


alter table public.donations enable row level security;
alter table public.receivers enable row level security;
alter table public.admin_accounts enable row level security;

drop policy if exists "food_bridge_donations_all" on public.donations;
create policy "food_bridge_donations_all"
on public.donations for all to anon
using (true) with check (true);

drop policy if exists "food_bridge_receivers_all" on public.receivers;
create policy "food_bridge_receivers_all"
on public.receivers for all to anon
using (true) with check (true);

drop policy if exists "food_bridge_admin_accounts_all" on public.admin_accounts;
create policy "food_bridge_admin_accounts_all"
on public.admin_accounts for all to anon
using (true) with check (true);

drop policy if exists "food_bridge_donor_accounts_all" on public.donor_accounts;
create policy "food_bridge_donor_accounts_all"
on public.donor_accounts for all to anon
using (true) with check (true);

